#!/usr/bin/env node
// Build supabase/apply-2026-09-15.sql from the migrations it is made of.
//
// The apply file is what Marc pastes into the Supabase SQL editor. It has to
// be the same bytes as the migrations, otherwise the thing that ran live and
// the thing in the repo drift apart and nobody notices for three months.
//
// Usage:
//   node scripts/supabase-build-apply.mjs           write the apply file
//   node scripts/supabase-build-apply.mjs --check   fail if it is out of date
//
// No dependencies. Node 18 or newer.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..');
const migrationsDir = join(repoRoot, 'supabase', 'migrations');
const outFile = join(repoRoot, 'supabase', 'apply-2026-09-15.sql');

// Order matters: leads first, then the profiles lockdown.
const PARTS = [
  '20260915000100_leads.sql',
  '20260915000200_profiles_rpc.sql',
];

const HEADER = [
  '-- Paste into the Supabase SQL editor. Safe to run twice.',
  '--',
  '-- Generated by scripts/supabase-build-apply.mjs. Do not edit by hand:',
  '-- edit the migrations under supabase/migrations/ and run the script again.',
  '--',
  `-- Parts, in order: ${PARTS.join(', ')}`,
  '',
].join('\n');

function build() {
  let out = HEADER;
  for (const name of PARTS) {
    const body = readFileSync(join(migrationsDir, name), 'utf8');
    out += `\n-- ${'='.repeat(68)}\n-- ${name}\n-- ${'='.repeat(68)}\n\n`;
    out += body;
    if (!body.endsWith('\n')) out += '\n';
  }
  return out;
}

const built = build();
const check = process.argv.includes('--check');

if (check) {
  let current = null;
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    current = null;
  }
  if (current === built) {
    console.log('apply-2026-09-15.sql is up to date.');
    process.exit(0);
  }
  console.error('apply-2026-09-15.sql is out of date. Run: node scripts/supabase-build-apply.mjs');
  process.exit(1);
}

writeFileSync(outFile, built, 'utf8');
console.log(`Wrote supabase/apply-2026-09-15.sql (${built.length} bytes, ${PARTS.length} migrations).`);
